"""Phase 1 report: candidate cloud-sea labels, base rates by month, example days, and a check against dated photos."""
from __future__ import annotations

from pathlib import Path

import pandas as pd

from cloudsea import label, metar
from cloudsea.settings import DATA_DIR, ROOT

MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def build_dawn() -> pd.DataFrame:
    dawn = metar.dawn_summary(metar.load(DATA_DIR / "raw" / "iem"))
    atmos = pd.read_parquet(DATA_DIR / "interim" / "label_atmosphere.parquet")
    d = label.attach_atmosphere(dawn, atmos)
    for name in label.DEFINITIONS:
        d[name] = label.label(d, name)
    d.to_parquet(DATA_DIR / "interim" / "dawn.parquet")
    return d


def base_rates(d: pd.DataFrame) -> str:
    sub = d[d.index >= "2021-04-01"]
    rates = sub.groupby(sub.index.month)[list(label.DEFINITIONS)].agg(["mean", "count"])
    lines = ["| Month | " + " | ".join(label.DEFINITIONS) + " |", "|---" * (len(label.DEFINITIONS) + 1) + "|"]
    for m, row in rates.iterrows():
        cells = [f"{100 * row[(k, 'mean')]:.0f}% (n={int(row[(k, 'count')])})" for k in label.DEFINITIONS]
        lines.append(f"| {MONTHS[m - 1]} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def examples(d: pd.DataFrame, name: str, n: int = 5) -> str:
    season = d[(d.index >= "2021-10-01") & d.index.month.isin([10, 11, 12, 1, 2]) & (d[name] == 1)]
    pick = season.sample(min(n, len(season)), random_state=7).sort_index()
    rows = [f"- **{day:%a %d %b %Y}**: RH850 {r.rh850:.0f}%, min vis {r.min_vis_m:.0f} m, "
            f"lowest ceiling {r.min_ceiling_ft:.0f} ft. `{r.metars[:150]}`" for day, r in pick.iterrows()]
    return "\n".join(rows)


def photo_check(d: pd.DataFrame) -> tuple[str, pd.DataFrame]:
    ref = pd.read_csv(ROOT / "docs" / "phase1" / "photo_reference_labels.csv", parse_dates=["date"])
    j = ref.set_index("date").join(d, how="left")
    j["airport_rule"] = label.low_layer(j)
    usable = j[j["airport_rule"].notna()]
    tab = pd.crosstab(usable["label"], usable["airport_rule"].astype(int).map({0: "rule: no", 1: "rule: sea"}))
    return tab.to_markdown(), j


def main() -> None:
    d = build_dawn()
    tab, j = photo_check(d)
    parts = [
        "# Phase 1: what counts as a cloud sea",
        "",
        "Generated by `make label-report` (`cloudsea/analysis/label_report.py`).",
        "Definitions are in `cloudsea/label.py`. The chosen one is `LABEL = \"" + label.LABEL + "\"`.",
        "",
        "## Base rates by month (2021-04 to 2026-10, share of usable dawns)",
        "",
        base_rates(d),
        "",
        "## Five example days per definition (fog season, random sample)",
    ]
    for name in label.DEFINITIONS:
        parts += ["", f"### {name}", "", examples(d, name)]
    parts += [
        "", "## Check against dated photos from the summit", "",
        "31 mornings with a Wikimedia Commons photo whose EXIF capture time is 05:00-08:59 and that shows the "
        "view below (`photo_reference_labels.csv`, labels by eye). 29 have enough airport reports to judge. "
        "Most are 2014-2019, before the 850 hPa data starts, so this checks the airport part of the label "
        "(definition A), not the summit-humidity part.", "", tab, "",
    ]
    parts += [
        "## Decision", "",
        "**B_low_layer_summit_clear**: at least two of the airport's dawn reports show fog, visibility under "
        "1500 m, or a broken/overcast ceiling at or below 1000 ft (about 300 m, well under the summit, which is "
        "~563 m above the airport); no rain; and the model's 850 hPa humidity at 06:30 IST is below 90%, so "
        "the summit is more likely above the layer than inside it.",
        "",
        "- A alone fires on monsoon stratus (23% of July dawns). On those days the photos show the summit "
        "inside the cloud. The 850 hPa term removes most of them (7% in July) and changes little in the fog "
        "season.",
        "- C is the cleanest physically, but it rejects most of the mornings photographed as cloud seas "
        "(fog in two reports is rare even on good days), so the model would learn from very few positives.",
        "- On the photo check, the airport part of B said 'sea' on 6 mornings and 5 of them were cloud seas; "
        "it found 5 of the 9 photographed cloud seas and never fired on the 6 socked-in or 3 partial mornings.",
        "",
        "## What this label can't know", "",
        "- **Cloud tops.** The airport sees the base of a layer, not its top. A thick layer can bury the summit "
        "(socked in); a thin one can show as patchy fog.",
        "- **Valley fog the airport misses.** The airport is 15 km south-east of the hill. Fog in the valleys "
        "to the north and west can make a sea at Nandi while the airport is clear (2017-02-11 in the photo "
        "check is probably this).",
        "- **Timing.** The window is 05:30-07:30 IST at half-hourly reports. Fog that forms after 07:30 or "
        "lifts before sunrise is miscounted.",
        "- **The 850 hPa humidity is a model estimate,** one grid cell, not a measurement at the summit.",
        "- **Haze vs cloud.** Thick haze over the plains can look like a sea in photos and is not a low layer "
        "in the reports.",
        "- **The photo check is small** (29 mornings), labelled by one person by eye, mostly before 2021, "
        "and trusts each camera's clock. It's a sanity check, not a validation.",
        "",
        "That gap is why the live app collects summit photos and grades every call against both the airport "
        "and the photos.",
    ]
    out = ROOT / "docs" / "phase1" / "label_report.md"
    out.write_text("\n".join(parts) + "\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
